package com.vodianoy.pgvc.cli;

import com.vodianoy.pgvc.diff.ChangeItem;
import com.vodianoy.pgvc.diff.SchemaDiffResult;
import com.vodianoy.pgvc.safety.RiskLevel;
import com.vodianoy.pgvc.safety.SafetyReport;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Markdown report of a schema diff for a Merge Request / Pull Request comment: summary, a table of the changes with
 * their risk (Migration Safety &amp; Lock Analyzer), warnings and the UP / DOWN SQL in collapsible blocks.
 */
public final class MarkdownReport {

    /** GitLab notes are limited to 1 000 000 characters, GitHub comments to 65 536: SQL beyond this is cut. */
    static final int MAX_SQL_CHARS = 40_000;

    private MarkdownReport() {
    }

    /**
     * @param title   first heading
     * @param context lines under the heading (database, target ...), already Markdown
     */
    public static String render(String title, List<String> context, SchemaDiffResult diff) {
        StringBuilder md = new StringBuilder();
        md.append("## 🐘 ").append(title).append("\n\n");
        for (String line : context) {
            md.append(line).append("  \n");
        }
        List<ChangeItem> changes = diff.getChanges();
        if (changes.isEmpty()) {
            md.append("\n✅ **No schema differences.**\n");
            return md.toString();
        }
        int dangerous = count(changes, RiskLevel.DANGEROUS);
        int warning = count(changes, RiskLevel.WARNING);
        int safe = changes.size() - dangerous - warning;
        md.append("**Changes:** ").append(changes.size())
                .append(" · 🔴 ").append(dangerous).append(" dangerous")
                .append(" · 🟡 ").append(warning).append(" warning")
                .append(" · 🟢 ").append(safe).append(" safe\n\n");

        md.append("| | Change | Object | Risk | Lock | Table size | Details |\n");
        md.append("|---|---|---|---|---|---|---|\n");
        for (ChangeItem c : changes) {
            SafetyReport s = c.getSafety();
            md.append("| ").append(icon(c)).append(" | ").append(c.getChangeType())
                    .append(" | `").append(cell(c.getObjectName())).append("` ").append(c.getObjectType().name().toLowerCase(Locale.ROOT))
                    .append(" | ").append(risk(s))
                    .append(" | ").append(s == null || s.getLockType() == null ? "—" : s.getLockType().label())
                    .append(" | ").append(size(s))
                    .append(" | ").append(cell(details(c))).append(" |\n");
        }

        Set<String> warnings = new LinkedHashSet<>(diff.getWarnings());
        for (ChangeItem c : changes) {
            if (c.getSafety() != null && c.getSafety().getRiskLevel() != RiskLevel.SAFE) {
                for (String note : c.getSafety().getNotes()) {
                    warnings.add("`" + c.getObjectName() + "`: " + note);
                }
            }
        }
        if (!warnings.isEmpty()) {
            md.append("\n### ⚠️ Warnings\n\n");
            for (String w : warnings) {
                md.append("- ").append(w.replace("\n", " ")).append('\n');
            }
        }
        List<String> patterns = new ArrayList<>();
        for (ChangeItem c : changes) {
            if (c.getSafety() != null && c.getSafety().getZeroDowntimeAlternativeSql() != null) {
                patterns.add("**`" + c.getObjectName() + "`**\n\n```sql\n" + c.getSafety().getZeroDowntimeAlternativeSql().strip()
                        + "\n```\n");
            }
        }
        if (!patterns.isEmpty()) {
            md.append("\n<details><summary>⚡ Zero-downtime alternatives (").append(patterns.size()).append(")</summary>\n\n");
            patterns.forEach(p -> md.append(p).append('\n'));
            md.append("</details>\n");
        }
        sqlBlock(md, "UP SQL", diff.getUpSql());
        sqlBlock(md, "DOWN SQL", diff.getDownSql());
        md.append("\n<sub>Generated by PgGitVisualizer (pg-git-vc --cli).</sub>\n");
        return md.toString();
    }

    /** Highest risk of the changes. */
    public static RiskLevel highestRisk(List<ChangeItem> changes) {
        RiskLevel max = RiskLevel.SAFE;
        for (ChangeItem c : changes) {
            if (c.getSafety() != null && c.getSafety().getRiskLevel().ordinal() > max.ordinal()) {
                max = c.getSafety().getRiskLevel();
            }
        }
        return max;
    }

    private static void sqlBlock(StringBuilder md, String title, String sql) {
        String s = sql == null ? "" : sql.strip();
        boolean cut = s.length() > MAX_SQL_CHARS;
        if (cut) {
            s = s.substring(0, MAX_SQL_CHARS) + "\n-- … (cut: " + (sql.strip().length() - MAX_SQL_CHARS) + " more characters)";
        }
        md.append("\n<details><summary>").append(title).append("</summary>\n\n```sql\n").append(s.replace("```", "`\u200b``"))
                .append("\n```\n</details>\n");
    }

    private static int count(List<ChangeItem> changes, RiskLevel level) {
        return (int) changes.stream().filter(c -> c.getSafety() != null && c.getSafety().getRiskLevel() == level).count();
    }

    private static String icon(ChangeItem c) {
        return switch (c.getChangeType()) {
            case ADDED -> "➕";
            case DELETED -> "➖";
            case RENAMED -> "✏️";
            case MODIFIED -> "🔧";
        };
    }

    private static String risk(SafetyReport s) {
        if (s == null) {
            return "—";
        }
        return switch (s.getRiskLevel()) {
            case DANGEROUS -> "🔴 DANGEROUS";
            case WARNING -> "🟡 WARNING";
            case SAFE -> "🟢 SAFE";
        } + (s.isCausesDataLoss() ? " · data loss" : "") + (s.isCausesTableRewrite() ? " · rewrite" : "");
    }

    private static String size(SafetyReport s) {
        if (s == null || s.getPrettySize() == null) {
            return "—";
        }
        return s.getPrettySize() + (s.getEstimatedRows() == null ? "" : " / " + s.getEstimatedRows() + " rows")
                + (s.getEstimatedDurationHint() == null ? "" : " · " + s.getEstimatedDurationHint());
    }

    private static String details(ChangeItem c) {
        return c.getDetails() == null ? "" : c.getDetails();
    }

    /** Text that is safe inside a Markdown table cell. */
    static String cell(String s) {
        return s == null ? "" : s.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ");
    }
}
